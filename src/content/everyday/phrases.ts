import type { EverydayPhrase } from '../../domain/everyday'

type PhraseSense = EverydayPhrase['senses'][number]
type ContextExample = [en: string, th: string, note: string]
type Correction = [wrong: string, right: string, note: string]
type Similar = [term: string, note: string]
type Mode = 'separable' | 'intransitive' | 'prepositional' | 'three-part' | 'literal'
type SenseDraft = Omit<PhraseSense, 'structure' | 'object' | 'placement' | 'pronoun'> & {
  mode: Mode
  placement?: string
  pronoun?: string
}

function sense(
  id: string, mode: Mode, meaning: string, context: string, when: string,
  situations: string[], collocations: string[], patterns: string[],
  examples: ContextExample[], similar: Similar[], mistake: Correction,
  details: { register?: PhraseSense['register']; placement?: string; pronoun?: string } = {},
): SenseDraft {
  const [wrong, right, note] = mistake
  return {
    id, mode, meaning, context, when, situations, collocations, patterns,
    examples: examples.map(([en, th, note]) => ({ en, th, note })),
    similar: similar.map(([term, note]) => ({ term, note })),
    mistakes: [{ wrong, right, note }], register: details.register ?? 'neutral',
    placement: details.placement, pronoun: details.pronoun,
  }
}

const structure: Record<Mode, PhraseSense['structure']> = {
  separable: 'phrasal',
  intransitive: 'phrasal',
  prepositional: 'prepositional',
  'three-part': 'phrasal-prepositional',
  literal: 'verb-combination',
}

function phrase(term: string, level: EverydayPhrase['level'], items: SenseDraft[]): EverydayPhrase {
  const [baseVerb, ...particles] = term.split(' ')
  const id = `everyday-phrase-${term.replaceAll(' ', '-')}`
  const senses = items.map(({ mode, placement, pronoun, ...item }): PhraseSense => {
    const object = mode === 'separable' ? 'separable' : mode === 'intransitive' ? 'none' : 'fixed'
    const particle = particles.join(' ')
    return {
      ...item, object, structure: structure[mode],
      placement: placement ?? (
        object === 'separable' ? `กรรมที่เป็นคำนามเต็มวางหลัง ${particle} หรือคั่นระหว่าง ${baseVerb} กับ ${particle} ได้`
          : object === 'fixed' ? `กรรมวางหลัง ${particle} ในความหมายนี้`
          : 'ใช้วลีนี้ได้โดยไม่มีกรรมตรง วลีบอกเวลา สถานที่ หรือส่วนขยายอื่นเติมต่อได้'
      ),
      pronoun: pronoun ?? (
        object === 'separable' ? `กรรมที่เป็นสรรพนาม เช่น it หรือ them ต้องคั่นระหว่าง ${baseVerb} กับ ${particle}`
          : object === 'fixed' ? `สรรพนามที่ทำหน้าที่เป็นกรรมอยู่หลัง ${particle} เช่น ${term} it เมื่อ it อ้างถึงสิ่งที่เหมาะกับวลี`
          : 'ไม่มีสรรพนามกรรมให้คั่นกลางในความหมายนี้'
      ),
    }
  })
  return {
    id, term, baseVerb, level, senses,
    exercises: senses.map((item, index) => {
      const { wrong, right, note } = item.mistakes[0]
      return {
        id: `${id}-${item.id}-choice`, kind: 'choice', difficulty: 'recognition',
        prompt: `${item.context} เลือกประโยคที่ใช้วลีได้ตรงความหมายและวางคำถูกตำแหน่ง`,
        options: index % 2 ? [right, wrong] : [wrong, right], answers: [right],
        hint: item.placement, explanation: note,
        feedback: { [wrong]: item.pronoun },
      }
    }),
  }
}

