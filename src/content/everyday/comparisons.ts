import type { EverydayComparison } from '../../domain/everyday'

type Example = [en: string, th: string, note: string]
type Mistake = [wrong: string, right: string, note: string]
type Option = [answer: string, reason: string]

function compare(
  slug: string, title: string, situation: string, distinction: string, naturalChoice: string,
  examples: Example[], mistakes: Mistake[],
  prompt: string, answer: string, options: Option[], explanation: string, hint: string,
): EverydayComparison {
  const id = `everyday-compare-${slug}`
  return {
    id, title, situation, distinction, naturalChoice,
    examples: examples.map(([en, th, note]) => ({ en, th, note })),
    mistakes: mistakes.map(([wrong, right, note]) => ({ wrong, right, note })),
    exercise: {
      id: `${id}-choice`, kind: 'choice', prompt, answers: [answer], difficulty: 'recognition',
      options: options.map(([value]) => value), hint, explanation,
      feedback: Object.fromEntries(options.filter(([value]) => value !== answer)),
    },
  }
}

