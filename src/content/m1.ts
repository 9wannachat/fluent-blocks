export const lessons: Lesson[] = lessonRows.map((row) => {
  const { id } = row
  const [prerequisite, objective, tagList, dialogueStart, dialogueReply] = lessonDetails[id]
  return {
    id, module: row.part, titleEn: row.en, titleTh: row.th, hook: row.hook, objective,
    concept: row.concept, formula: row.formula, minutes: 8,
    prerequisites: prerequisite ? [prerequisite] : [], tags: tagList.split(','),
    examples: row.examples.map(([en, th, note]) => ({ en, th, note })),
    contrasts: row.contrasts.map(([a, b, note]) => ({ a, b, note })),
    dialogue: [{ en: row.dialogue[0], th: dialogueStart }, { en: row.dialogue[1], th: dialogueReply }],
    mistakes: [{ wrong: row.mistake[0], right: row.mistake[1], note: row.mistake[2] }],
    exercises: row.exercises.map(([prompt, answers, explanation], exerciseIndex) => {
      const exerciseId = `${id}-e${exerciseIndex + 1}`
      const feedback = feedbackByExercise[exerciseId]
      const kind = exerciseKind(prompt)
      const options = kind === 'order' ? prompt.replace('เรียงคำ: ', '').split(' / ') : undefined
      return {
        id: exerciseId, kind, prompt, answers: [...answers], ...(options ? { options } : {}),
        difficulty: kind === 'fill' ? 'recognition' : kind === 'translate' ? 'production' : 'guided',
        hint: row.formula, explanation, ...(feedback ? { feedback } : {}),
      }
    }),
    speaking: row.speaking,
    review: patternRows.flatMap(([patternId, lessonId]) => lessonId === id ? [patternId] : []),
  }
})
