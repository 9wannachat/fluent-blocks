import type { Exercise } from '../../domain/content'
import { practicalLesson, practicalScenario } from './authoring'
import type { PracticalLesson } from '../../domain/practical'

type Example = PracticalLesson['examples'][number]
type Vocabulary = PracticalLesson['vocabulary'][number]
type Prompt = Omit<Exercise, 'id'>
type LessonDraft = Omit<PracticalLesson, 'id' | 'moduleId' | 'exercises'> & { exercises: Prompt[] }

const model = (en: string, th: string, note: string): Example => ({ en, th, note })
const turn = (en: string, th: string) => ({ en, th })
const contrast = (a: string, b: string, note: string) => ({ a, b, note })
const mistake = (wrong: string, right: string, note: string) => ({ wrong, right, note })
const word = (
  term: string, pronunciation: string, meaning: string, context: string,
  forms?: string[], register?: Vocabulary['register'], variant?: Vocabulary['variant'],
): Vocabulary => ({ term, pronunciation, meaning, context, forms, register, variant })

function choose(
  prompt: string, options: string[], answer: string, hint: string, explanation: string, feedback?: Record<string, string>,
): Prompt {
  return { kind: 'choice', prompt, options, answers: [answer], hint, explanation, feedback, difficulty: 'recognition' }
}

function arrange(prompt: string, options: string[], answers: string[], hint: string, explanation: string): Prompt {
  return { kind: 'order', prompt, options, answers, hint, explanation, difficulty: 'guided' }
}

function write(
  kind: 'fill' | 'translate' | 'repair' | 'transform', prompt: string, answers: string[], hint: string,
  explanation: string, feedback?: Record<string, string>,
): Prompt {
  return { kind, prompt, answers, hint, explanation, feedback, difficulty: 'production' }
}

function dining(slug: string, draft: LessonDraft): PracticalLesson {
  const id = `practical-dining-${slug}`
  return {
    ...draft, id, moduleId: 'dining',
    exercises: draft.exercises.map((exercise, index) => ({ ...exercise, id: `${id}-e${index + 1}` })),
  }
}

